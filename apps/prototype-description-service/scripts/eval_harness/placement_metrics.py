"""Spatial-relation placement correctness (VLM-6 S1). Pure, no network.

Scores caption placement claims against ``SpatialFact`` ground truth derived from
curated face/object boxes. Deterministic + precision-first (LLM-judge is out of
MVP): a fact's ``phrases`` are the CORRECT placement claims; the same phrases with
their directional word inverted (left<->right, above<->below, top<->bottom,
foreground<->background) are the WRONG placement claims. A caption is only scored
for a fact when it actually asserts one of those directional phrases — silence is
never counted, so a model is never penalized for omitting a placement it never
claimed. Placement accuracy is reported ALONGSIDE the fabricated-fact rate, never
folded into it (a wrong placement is a distinct error class).
"""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass, field

from scripts.eval_harness.caption_metrics import contains_phrase
from scripts.eval_harness.manifest import SpatialFact

# Whole-word directional inversions. Kept to unambiguous single-token swaps so an
# inverted phrase is generated by substitution without reparsing (precision-first;
# ambiguous terms like "behind"/"front" are intentionally excluded).
_INVERT = {
    "left": "right",
    "right": "left",
    "above": "below",
    "below": "above",
    "top": "bottom",
    "bottom": "top",
    "foreground": "background",
    "background": "foreground",
}


def _invert_phrase(phrase: str) -> str | None:
    """Swap the directional token(s) in a phrase; None if it has no directional word."""
    tokens = phrase.split()
    swapped = False
    out: list[str] = []
    for token in tokens:
        lowered = token.lower()
        if lowered in _INVERT:
            replacement = _INVERT[lowered]
            out.append(replacement.capitalize() if token[:1].isupper() else replacement)
            swapped = True
        else:
            out.append(token)
    return " ".join(out) if swapped else None


@dataclass(frozen=True)
class PlacementScores:
    correct: list[str] = field(default_factory=list)  # fact texts the caption placed correctly
    wrong: list[tuple[str, str]] = field(default_factory=list)  # (fact text, matched inverted phrase)

    @property
    def claims(self) -> int:
        return len(self.correct) + len(self.wrong)

    @property
    def accuracy(self) -> float | None:
        """Correct / asserted placement claims (None when the caption made no claim)."""
        return len(self.correct) / self.claims if self.claims else None


def score_placement(caption: str, *, spatial_facts: Sequence[SpatialFact]) -> PlacementScores:
    """Score placement claims in ``caption`` against ``spatial_facts``.

    Per fact: if the caption states a correct phrase -> correct; else if it states
    an inverted (wrong-direction) phrase -> wrong; else the fact is not asserted
    and is skipped. Correct wins over wrong when a caption somehow states both.
    """
    correct: list[str] = []
    wrong: list[tuple[str, str]] = []
    for fact in spatial_facts:
        targets = [p for p in fact.phrases if p.strip()]
        if not targets:
            continue  # no matchable placement phrase authored — cannot score this fact
        if any(contains_phrase(caption, t) for t in targets):
            correct.append(fact.text)
            continue
        inverted = [inv for t in targets if (inv := _invert_phrase(t)) is not None]
        hit = next((inv for inv in inverted if contains_phrase(caption, inv)), None)
        if hit is not None:
            wrong.append((fact.text, hit))
    return PlacementScores(correct=correct, wrong=wrong)


def placement_accuracy(scores: Sequence[PlacementScores]) -> float | None:
    """Micro placement accuracy: total correct / total asserted claims (None if no claims)."""
    correct = sum(len(s.correct) for s in scores)
    claims = sum(s.claims for s in scores)
    return correct / claims if claims else None
