"""Spatial-relation placement correctness (VLM-6 S1). Pure, no network.

Scores caption placement claims against ``SpatialFact`` ground truth derived from
curated face/object boxes. Deterministic + precision-first (LLM-judge is out of
MVP). Placement accuracy is reported ALONGSIDE the fabricated-fact rate, never
folded into it (a wrong placement is a distinct error class).

Spatial relations are image/viewer-left (increasing centre-x is rightward), never
the subject's anatomical left.

Observables (MEAS-11 / VLM6-R4-03)
---------------------------------
Define these before reading any number the metric emits:

**Applicable fact**
    Every ``SpatialFact`` in the scorer input is applicable. Scoring uses the
    fact's ``relation`` + ``subject`` / ``reference`` / ``reference2`` structure.
    Authored ``phrases`` are optional near-verbatim hints (and their
    directional inversions); they are not required for a fact to enter the
    denominator.

**Claim (correct)**
    The caption asserts the *correct* placement for an applicable fact. Matched
    either by a near-verbatim authored phrase, or by structural paraphrase
    detection (entity pair + directional term, or subject-centric absolute
    placement language such as "on the left").

**Claim (error / wrong)**
    The caption asserts a *contradictory* placement for an applicable fact
    (token-swapped inversion of an authored phrase, structure-derived wrong
    between-claim, or structural paraphrase of the opposite direction). Wrong
    claims enter the accuracy denominator and drive the score toward 0.0.

**Abstention**
    An applicable fact for which the caption makes **no** placement claim
    (neither correct nor wrong). Silence is never counted as error — but the
    abstention is **reported** on ``PlacementScores.abstained`` (UXR-15,
    UXR-07), not silently dropped from the result object.

**placement_accuracy → None vs 0.0**
    * ``None`` means **no claims were asserted** across the scored items
      (only abstentions, or no applicable facts). It is "no accuracy
      observable", not a perfect score and not a zero score.
    * ``0.0`` means claims were asserted and **all of them were wrong**.
    Callers that need coverage must read ``abstained`` / claim counts; they
    must not treat ``None`` as 0.0 or as 1.0.

Matching policy (precision-first paraphrase)
--------------------------------------------
1. Near-verbatim authored phrase → correct (wins over wrong if both present).
2. Near-verbatim inverted phrase, or BETWEEN structure-derived wrong middle
   entity → wrong.
3. Structural pair order: ``subject … dir … reference`` (or the inverse
   wording ``reference … opposite_dir … subject``) → correct/wrong by
   polarity. Catches "Alice is left of Bob" and "Bob is to the left of Alice".
4. Structural absolute: subject near "on the left" / "to the right" /
   "in the foreground" etc. → correct/wrong by polarity. Catches
   "the man stands on the right" when the fact is man LEFT_OF woman.
5. Else → abstention for that fact.

A model that paraphrases placement can score badly (wrong) or well (correct);
it can no longer vanish into ``None`` merely by avoiding the authored string.
"""

from __future__ import annotations

import re
import string
from collections.abc import Sequence
from dataclasses import dataclass, field
from typing import Literal

from scripts.eval_harness.caption_metrics import contains_phrase
from scripts.eval_harness.manifest import SpatialFact, SpatialRelation

# Whole-word directional inversions. Kept to unambiguous single-token swaps so an
# inverted phrase is generated by substitution without reparsing (precision-first;
# ambiguous terms like "behind"/"front" are intentionally excluded from inversion
# generation — absolute synonym matching below is separate and multi-word).
_INVERT = {
    "left": "right",
    "right": "left",
    "above": "below",
    "below": "above",
    "top": "bottom",
    "bottom": "top",
    "foreground": "background",
    "background": "foreground",
}

# Char window for structural entity…dir…entity / subject…absolute patterns.
_STRUCT_WINDOW = 80

# Canonical direction token for each binary / depth relation (single primary
# token used in pair-order patterns). Synonyms handled via absolute patterns
# and the small pair-term sets below.
_REL_PRIMARY_DIR: dict[SpatialRelation, str] = {
    SpatialRelation.LEFT_OF: "left",
    SpatialRelation.RIGHT_OF: "right",
    SpatialRelation.ABOVE: "above",
    SpatialRelation.BELOW: "below",
    SpatialRelation.FOREGROUND: "foreground",
    SpatialRelation.BACKGROUND: "background",
}

_OPPOSITE_REL: dict[SpatialRelation, SpatialRelation] = {
    SpatialRelation.LEFT_OF: SpatialRelation.RIGHT_OF,
    SpatialRelation.RIGHT_OF: SpatialRelation.LEFT_OF,
    SpatialRelation.ABOVE: SpatialRelation.BELOW,
    SpatialRelation.BELOW: SpatialRelation.ABOVE,
    SpatialRelation.FOREGROUND: SpatialRelation.BACKGROUND,
    SpatialRelation.BACKGROUND: SpatialRelation.FOREGROUND,
}

# Pair-order mid terms for entity…dir…entity matching (VLM6-B-06).
# Bare "left"/"right" are intentionally excluded: "Alice left Bob at the
# station" is a departure verb, not a placement claim. Absolute patterns
# already avoid bare left/right for the same reason. Require unambiguous
# placement constructions; longer phrases first so "to the left of" wins
# over "left of". FOREGROUND/BACKGROUND use absolute multi-word patterns only.
_PAIR_DIR_TERMS: dict[str, tuple[str, ...]] = {
    "left": ("to the left of", "left of"),
    "right": ("to the right of", "right of"),
    "above": ("above", "over"),
    "below": ("below", "under"),
}

# Multi-word absolute placement cues. Bare "left"/"right" alone are NOT used
# here so "Alice left the room" does not invent a placement claim.
_ABS_DIR_PATTERNS: dict[str, tuple[str, ...]] = {
    "left": (
        r"on the left",
        r"to the left",
        r"at the left",
        r"leftmost",
    ),
    "right": (
        r"on the right",
        r"to the right",
        r"at the right",
        r"rightmost",
    ),
    "above": (
        r"on top",
        r"at the top",
        r"above",
    ),
    "below": (
        r"at the bottom",
        r"underneath",
        r"below",
    ),
    "foreground": (
        r"in the foreground",
        r"in the front",
        r"at the front",
    ),
    "background": (
        r"in the background",
        r"in the back",
        r"at the back",
    ),
}


def _invert_phrase(phrase: str) -> str | None:
    """Swap the directional token(s) in a phrase; None if it has no directional word.

    Punctuation-robust: a directional token carrying leading/trailing punctuation
    (``foreground.``, ``left,``) is matched on its stripped core and the punctuation
    is re-attached, so free-text ``SpatialFact.phrases`` keep yielding a wrong-claim
    phrase instead of silently returning None (VLM-6 S5 W3 / VLM6-D-02).
    """
    swapped = False
    out: list[str] = []
    for token in phrase.split():
        stripped_left = token.lstrip(string.punctuation)
        prefix = token[: len(token) - len(stripped_left)]
        core = stripped_left.rstrip(string.punctuation)
        suffix = stripped_left[len(core) :]
        lowered = core.lower()
        if core and lowered in _INVERT:
            replacement = _INVERT[lowered]
            replacement = replacement.capitalize() if core[:1].isupper() else replacement
            out.append(f"{prefix}{replacement}{suffix}")
            swapped = True
        else:
            out.append(token)
    return " ".join(out) if swapped else None


def _between_wrong_phrases(fact: SpatialFact) -> list[str]:
    """Structure-derived WRONG between-claims: a NON-subject entity placed in the
    middle. e.g. correct 'Alice between Bob and Carol' -> wrong 'Bob between Alice
    and Carol' / 'Carol between Alice and Bob'.

    The directional ``_INVERT`` swap cannot express this — ``between`` has no
    directional antonym — so without this a stated wrong between-claim scored as
    'no claim' (accuracy=None) and silently inflated placement accuracy for any
    image with a between-relation error (VLM-6 S5 W2 / VLM6-D-01).
    """
    subject, ref1, ref2 = fact.subject, fact.reference, fact.reference2
    if not (ref1 and ref2):
        return []  # malformed BETWEEN (the manifest validator normally forbids this)
    # Every ordering that puts a reference (not the subject) in the middle. Both
    # endpoint orders are enumerated so a caption's phrasing choice cannot dodge it.
    return [
        f"{ref1} between {subject} and {ref2}",
        f"{ref1} between {ref2} and {subject}",
        f"{ref2} between {subject} and {ref1}",
        f"{ref2} between {ref1} and {subject}",
    ]


def _between_correct_phrases(fact: SpatialFact) -> list[str]:
    """Structure-derived CORRECT between-claims (subject in the middle)."""
    subject, ref1, ref2 = fact.subject, fact.reference, fact.reference2
    if not (ref1 and ref2):
        return []
    return [
        f"{subject} between {ref1} and {ref2}",
        f"{subject} between {ref2} and {ref1}",
    ]


def _wb(text: str) -> str:
    """Regex fragment: word-boundary-safe literal."""
    return rf"(?<!\w){re.escape(text)}(?!\w)"


def _mid_pattern(mid: str) -> str:
    """Word-boundary pattern for a single- or multi-token pair mid term."""
    parts = mid.split()
    if len(parts) == 1:
        return _wb(parts[0])
    # Multi-word placement constructions ("to the left of"): boundary each token.
    return r"\s+".join(_wb(p) for p in parts)


def _ordered_triple(caption: str, left: str, mids: Sequence[str], right: str) -> str | None:
    """Return the mid term if ``left … mid … right`` appears within the window."""
    if not left or not right or not mids:
        return None
    for mid in mids:
        mid_pat = _mid_pattern(mid)
        pat = _wb(left) + rf".{{0,{_STRUCT_WINDOW}}}" + mid_pat + rf".{{0,{_STRUCT_WINDOW}}}" + _wb(right)
        if re.search(pat, caption, flags=re.IGNORECASE | re.DOTALL):
            return mid
    return None


def _absolute_cue_pattern(raw: str) -> str:
    """Word-boundary pattern for a single- or multi-token absolute placement cue."""
    parts = raw.split()
    if len(parts) == 1:
        return _wb(parts[0])
    return r"\s+".join(_wb(p) for p in parts)


def _subject_near_absolute(caption: str, subject: str, direction: str) -> str | None:
    """Return the absolute cue matched if subject appears near an absolute dir phrase."""
    patterns = _ABS_DIR_PATTERNS.get(direction)
    if not patterns or not subject:
        return None
    subj = _wb(subject)
    for raw in patterns:
        cue = _absolute_cue_pattern(raw)
        p_subj_then = subj + rf".{{0,{_STRUCT_WINDOW}}}" + cue
        p_cue_then = cue + rf".{{0,{_STRUCT_WINDOW}}}" + subj
        if re.search(p_subj_then, caption, flags=re.IGNORECASE | re.DOTALL):
            return raw
        if re.search(p_cue_then, caption, flags=re.IGNORECASE | re.DOTALL):
            return raw
    return None


def _pair_structural_verdict(caption: str, fact: SpatialFact) -> tuple[Literal["correct", "wrong"], str] | None:
    """Entity-pair + direction order for binary relations."""
    rel = fact.relation
    primary = _REL_PRIMARY_DIR.get(rel)
    if primary is None or primary not in _PAIR_DIR_TERMS:
        return None
    if not fact.reference:
        return None
    opp_rel = _OPPOSITE_REL[rel]
    opp_primary = _REL_PRIMARY_DIR[opp_rel]
    correct_mids = _PAIR_DIR_TERMS[primary]
    wrong_mids = _PAIR_DIR_TERMS[opp_primary]
    subject, reference = fact.subject, fact.reference

    # Correct: subject … correct_dir … reference  OR  reference … opposite_dir … subject
    hit = _ordered_triple(caption, subject, correct_mids, reference)
    if hit is not None:
        return "correct", f"structural:{subject} {hit} {reference}"
    hit = _ordered_triple(caption, reference, wrong_mids, subject)
    if hit is not None:
        return "correct", f"structural:{reference} {hit} {subject}"

    # Wrong: subject … opposite_dir … reference  OR  reference … correct_dir … subject
    hit = _ordered_triple(caption, subject, wrong_mids, reference)
    if hit is not None:
        return "wrong", f"structural:{subject} {hit} {reference}"
    hit = _ordered_triple(caption, reference, correct_mids, subject)
    if hit is not None:
        return "wrong", f"structural:{reference} {hit} {subject}"
    return None


def _absolute_structural_verdict(caption: str, fact: SpatialFact) -> tuple[Literal["correct", "wrong"], str] | None:
    """Subject-centric absolute placement (on the left / in the foreground / …)."""
    rel = fact.relation
    primary = _REL_PRIMARY_DIR.get(rel)
    if primary is None:
        return None
    opp = _OPPOSITE_REL.get(rel)
    opp_primary = _REL_PRIMARY_DIR.get(opp) if opp is not None else None

    correct_hit = _subject_near_absolute(caption, fact.subject, primary)
    wrong_hit = _subject_near_absolute(caption, fact.subject, opp_primary) if opp_primary else None
    if correct_hit and not wrong_hit:
        return "correct", f"structural-abs:{fact.subject} {correct_hit}"
    if wrong_hit and not correct_hit:
        return "wrong", f"structural-abs:{fact.subject} {wrong_hit}"
    if correct_hit and wrong_hit:
        # Both absolute cues: prefer correct (mirrors phrase-path policy).
        return "correct", f"structural-abs:{fact.subject} {correct_hit}"
    return None


def _structural_verdict(caption: str, fact: SpatialFact) -> tuple[Literal["correct", "wrong"], str] | None:
    """Paraphrase path: pair order first, then absolute subject-centric cues."""
    if fact.relation is SpatialRelation.BETWEEN:
        for phrase in _between_correct_phrases(fact):
            if contains_phrase(caption, phrase):
                return "correct", phrase
        for phrase in _between_wrong_phrases(fact):
            if contains_phrase(caption, phrase):
                return "wrong", phrase
        return None

    if fact.relation in (SpatialRelation.FOREGROUND, SpatialRelation.BACKGROUND):
        return _absolute_structural_verdict(caption, fact)

    pair = _pair_structural_verdict(caption, fact)
    if pair is not None:
        return pair
    return _absolute_structural_verdict(caption, fact)


@dataclass(frozen=True)
class PlacementScores:
    correct: list[str] = field(default_factory=list)  # fact texts the caption placed correctly
    wrong: list[tuple[str, str]] = field(default_factory=list)  # (fact text, matched evidence)
    abstained: list[str] = field(default_factory=list)  # applicable facts with no claim

    @property
    def claims(self) -> int:
        return len(self.correct) + len(self.wrong)

    @property
    def accuracy(self) -> float | None:
        """Correct / asserted placement claims (None when the caption made no claim)."""
        return len(self.correct) / self.claims if self.claims else None


def score_placement(caption: str, *, spatial_facts: Sequence[SpatialFact]) -> PlacementScores:
    """Score placement claims in ``caption`` against ``spatial_facts``.

    Per applicable fact:
    * correct phrase or structural correct paraphrase → correct
    * inverted phrase / structural wrong paraphrase → wrong
    * neither → abstention (reported on ``abstained``)

    Correct wins over wrong when a caption somehow states both. See module
    docstring for the full observable definitions (MEAS-11).
    """
    correct: list[str] = []
    wrong: list[tuple[str, str]] = []
    abstained: list[str] = []
    for fact in spatial_facts:
        targets = [p for p in fact.phrases if p.strip()]
        # 1) near-verbatim correct
        if targets and any(contains_phrase(caption, t) for t in targets):
            correct.append(fact.text)
            continue
        # 2) near-verbatim wrong (inversion + between-structure)
        inverted = [inv for t in targets if (inv := _invert_phrase(t)) is not None]
        if fact.relation is SpatialRelation.BETWEEN:
            inverted.extend(_between_wrong_phrases(fact))
        hit = next((inv for inv in inverted if contains_phrase(caption, inv)), None)
        if hit is not None:
            wrong.append((fact.text, hit))
            continue
        # 3-4) structural paraphrase (pair order / absolute / between structure)
        structural = _structural_verdict(caption, fact)
        if structural is not None:
            verdict, evidence = structural
            if verdict == "correct":
                correct.append(fact.text)
            else:
                wrong.append((fact.text, evidence))
            continue
        # 5) abstention — applicable but unclaimed
        abstained.append(fact.text)
    return PlacementScores(correct=correct, wrong=wrong, abstained=abstained)


def placement_accuracy(scores: Sequence[PlacementScores]) -> float | None:
    """Micro placement accuracy: total correct / total asserted claims.

    Returns ``None`` when no claims were asserted (no accuracy observable).
    Returns ``0.0`` when claims exist and all are wrong. Abstentions do not
    enter the denominator; sum ``len(s.abstained)`` for coverage.
    """
    correct = sum(len(s.correct) for s in scores)
    claims = sum(s.claims for s in scores)
    return correct / claims if claims else None
