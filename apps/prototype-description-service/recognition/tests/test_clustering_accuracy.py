import asyncio
import logging
import random
from typing import NamedTuple

import numpy as np
import pytest
from sklearn.metrics import adjusted_rand_score, completeness_score, homogeneity_score

from db.models import IdentityCluster, MediaIdentity
from recognition.application.clustering.chinese_whispers import ChineseWhispersClustering
from recognition.application.clustering.clustering_settings import ClusteringSettings

logger = logging.getLogger(__name__)


class SyntheticData(NamedTuple):
    identities: list[MediaIdentity]
    true_labels: list[int]
    num_people: int
    samples_per_person: int


def generate_synthetic_data(num_people=20, samples_per_person=10, noise_level=0.1) -> SyntheticData:
    """
    Generate synthetic face embeddings.
    Each person has a 'center' in 128-d space.
    Samples are generated by adding gaussian noise to the center.
    """
    np.random.seed(42)
    dim = 128
    identities = []
    true_labels = []

    for person_id in range(num_people):
        # Generate a random center on the unit hypersphere
        center = np.random.randn(dim)
        center /= np.linalg.norm(center)

        for _ in range(samples_per_person):
            # Add noise
            noise = np.random.randn(dim) * noise_level
            embedding = center + noise
            # Normalize
            embedding /= np.linalg.norm(embedding)

            identity = MediaIdentity(
                id=random.randint(10000, 99999),  # Mock ID
                media_id=random.randint(1000, 9999),
                embedding=embedding.tolist(),
                confidence=0.99,
            )
            identities.append(identity)
            true_labels.append(person_id)

    return SyntheticData(identities, true_labels, num_people, samples_per_person)


